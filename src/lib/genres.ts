export function layoutStage(instrumentIds: string[], seedStr = "stage"): Record<string, StagePos> {
  const rng = mulberry32(hashString(seedStr));
  const groups: Record<string, string[]> = {};
  for (const id of instrumentIds) {
    const fam = INSTRUMENT_MAP[id]?.family ?? "strings";
    (groups[fam] ??= []).push(id);
  }
  const out: Record<string, StagePos> = {};
  for (const [fam, ids] of Object.entries(groups)) {
    const band = FAMILY_BANDS[fam] ?? FAMILY_BANDS.strings;
    const n = ids.length;
    ids.forEach((id, i) => {
      const t = n === 1 ? 0.5 : i / (n - 1);
      const x = band.x0 + (band.x1 - band.x0) * t + (rng() - 0.5) * band.spread;
      const y = band.y + (rng() - 0.5) * band.spread + Math.abs(t - 0.5) * 0.06;
      out[id] = { x: Math.min(0.96, Math.max(0.04, x)), y: Math.min(0.94, Math.max(0.12, y)) };
    });
  }
  return out;
}

export function defaultChannels(instrumentIds: string[], stage: Record<string, StagePos>): Record<string, ChannelState> {
  const ch: Record<string, ChannelState> = {};
  for (const id of instrumentIds) {
    const def = INSTRUMENT_MAP[id];
    const pos = stage[id] ?? { x: 0.5, y: 0.5 };
    ch[id] = {
      volume: def?.vol ?? 0.75,
      pan: Math.max(-0.85, Math.min(0.85, (pos.x - 0.5) * 1.3)),
      mute: false,
      solo: false,
    };
  }
  return ch;
}

export const defaultChannel = (id: string): ChannelState => ({
  volume: INSTRUMENT_MAP[id]?.vol ?? 0.75,
  pan: 0,
  mute: false,
  solo: false,
});

