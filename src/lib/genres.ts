/* ---------- fusión de estilos ---------- */

export function fusedGenres(orch: Pick<Orchestra, "genreId" | "fusions">): GenreDef[] {
  const base = GENRE_MAP[orch.genreId] ?? GENRES[0];
  const extras = (orch.fusions ?? []).map((f) => GENRE_MAP[f]).filter(Boolean) as GenreDef[];
  return [base, ...extras];
}

export function fusedBpmRange(orch: Pick<Orchestra, "genreId" | "fusions">): [number, number] {
  const gs = fusedGenres(orch);
  const mn = Math.max(...gs.map((g) => g.bpmMin));
  const mx = Math.min(...gs.map((g) => g.bpmMax));
  return mn <= mx ? [mn, mx] : [gs[0].bpmMin, gs[0].bpmMax];
}

export function fusedLineup(orch: Pick<Orchestra, "genreId" | "fusions">): string[] {
  return [...new Set(fusedGenres(orch).flatMap((g) => g.lineup))];
}

